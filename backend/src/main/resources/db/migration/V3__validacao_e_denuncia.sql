-- Sprint 05: histórico de validações e denúncias, com dados mínimos.
-- validacao NÃO guarda o texto/token consultado, IP nem navegador: apenas o resultado
-- e referências opcionais. Retenção aplicada por tarefa agendada (app.retencao.*).

CREATE TABLE validacao (
    id                 UUID         PRIMARY KEY,
    resultado_interno  VARCHAR(20)  NOT NULL,
    status_publico     VARCHAR(16)  NOT NULL,
    token_id           BIGINT,
    vaga_id            BIGINT,
    criada_em          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_validacao_token FOREIGN KEY (token_id) REFERENCES token (id) ON DELETE SET NULL,
    CONSTRAINT fk_validacao_vaga FOREIGN KEY (vaga_id) REFERENCES vaga (id) ON DELETE SET NULL,
    CONSTRAINT ck_validacao_status CHECK (status_publico IN ('CONFIRMADO', 'NAO_CONFIRMADO')),
    CONSTRAINT ck_validacao_resultado CHECK (resultado_interno IN
        ('CONFIRMADO', 'NAO_ENCONTRADO', 'EXPIRADO', 'REVOGADO', 'VAGA_INATIVA', 'PREFIXO_DIVERGENTE', 'SEM_TOKEN'))
);

CREATE INDEX ix_validacao_criada_em ON validacao (criada_em);

CREATE TABLE denuncia (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocolo      VARCHAR(16)   NOT NULL,
    url_suspeita   VARCHAR(2048) NOT NULL,
    email_contato  VARCHAR(254),
    descricao      VARCHAR(2000) NOT NULL,
    validacao_id   UUID,
    aceite_aviso   BOOLEAN       NOT NULL,
    registrada_em  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_denuncia_protocolo UNIQUE (protocolo),
    -- Referência opcional: denúncia de oferta não cadastrada não depende de validação.
    CONSTRAINT fk_denuncia_validacao FOREIGN KEY (validacao_id) REFERENCES validacao (id) ON DELETE SET NULL,
    CONSTRAINT ck_denuncia_aceite CHECK (aceite_aviso = TRUE)
);

CREATE INDEX ix_denuncia_registrada_em ON denuncia (registrada_em);
