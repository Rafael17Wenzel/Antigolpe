-- Antigolpe — esquema inicial (Sprint 03)
-- SQL compatível com PostgreSQL 16 e H2 (modo PostgreSQL, usado nos testes).
-- Tokens nunca são guardados em claro: apenas o HMAC-SHA256 (hex) do valor normalizado.

CREATE TABLE regiao (
    uf      CHAR(2)     PRIMARY KEY,
    nome    VARCHAR(60) NOT NULL,
    CONSTRAINT uk_regiao_nome UNIQUE (nome)
);

CREATE TABLE categoria (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome    VARCHAR(100) NOT NULL,
    CONSTRAINT uk_categoria_nome UNIQUE (nome)
);

CREATE TABLE curso (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug          VARCHAR(60)  NOT NULL,
    titulo        VARCHAR(150) NOT NULL,
    descricao     TEXT         NOT NULL,
    categoria_id  BIGINT       NOT NULL,
    CONSTRAINT uk_curso_slug UNIQUE (slug),
    CONSTRAINT fk_curso_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id)
);

CREATE TABLE vaga (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug              VARCHAR(60)  NOT NULL,
    cargo             VARCHAR(120) NOT NULL,
    modalidade        VARCHAR(12)  NOT NULL,
    uf                CHAR(2),
    cidade            VARCHAR(100),
    fonte_cadastrada  VARCHAR(200) NOT NULL,
    situacao          VARCHAR(12)  NOT NULL,
    ficticia          BOOLEAN      NOT NULL DEFAULT TRUE,
    criada_em         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_vaga_slug UNIQUE (slug),
    CONSTRAINT fk_vaga_regiao FOREIGN KEY (uf) REFERENCES regiao (uf),
    CONSTRAINT ck_vaga_modalidade CHECK (modalidade IN ('PRESENCIAL', 'HIBRIDA', 'REMOTA')),
    CONSTRAINT ck_vaga_situacao CHECK (situacao IN ('RASCUNHO', 'PUBLICADA', 'ENCERRADA')),
    -- Vaga presencial ou híbrida precisa de UF; remota pode não ter.
    CONSTRAINT ck_vaga_uf_modalidade CHECK (modalidade = 'REMOTA' OR uf IS NOT NULL)
);

CREATE INDEX ix_vaga_uf_situacao ON vaga (uf, situacao);

CREATE TABLE vaga_curso (
    vaga_id   BIGINT   NOT NULL,
    curso_id  BIGINT   NOT NULL,
    ordem     SMALLINT NOT NULL,
    CONSTRAINT pk_vaga_curso PRIMARY KEY (vaga_id, curso_id),
    CONSTRAINT uk_vaga_curso_ordem UNIQUE (vaga_id, ordem),
    CONSTRAINT fk_vaga_curso_vaga FOREIGN KEY (vaga_id) REFERENCES vaga (id) ON DELETE CASCADE,
    CONSTRAINT fk_vaga_curso_curso FOREIGN KEY (curso_id) REFERENCES curso (id)
);

CREATE TABLE trilha (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug  VARCHAR(60)  NOT NULL,
    nome  VARCHAR(120) NOT NULL,
    CONSTRAINT uk_trilha_slug UNIQUE (slug)
);

CREATE TABLE trilha_curso (
    trilha_id  BIGINT   NOT NULL,
    curso_id   BIGINT   NOT NULL,
    ordem      SMALLINT NOT NULL,
    CONSTRAINT pk_trilha_curso PRIMARY KEY (trilha_id, curso_id),
    CONSTRAINT uk_trilha_curso_ordem UNIQUE (trilha_id, ordem),
    CONSTRAINT fk_trilha_curso_trilha FOREIGN KEY (trilha_id) REFERENCES trilha (id) ON DELETE CASCADE,
    CONSTRAINT fk_trilha_curso_curso FOREIGN KEY (curso_id) REFERENCES curso (id)
);

CREATE TABLE token (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vaga_id       BIGINT      NOT NULL,
    hash          CHAR(64)    NOT NULL,
    prefixo       VARCHAR(12) NOT NULL,
    final_visivel VARCHAR(4)  NOT NULL,
    ativo         BOOLEAN     NOT NULL DEFAULT TRUE,
    valido_de     TIMESTAMP WITH TIME ZONE NOT NULL,
    valido_ate    TIMESTAMP WITH TIME ZONE NOT NULL,
    revogado_em   TIMESTAMP WITH TIME ZONE,
    criado_em     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_token_hash UNIQUE (hash),
    CONSTRAINT fk_token_vaga FOREIGN KEY (vaga_id) REFERENCES vaga (id),
    CONSTRAINT ck_token_validade CHECK (valido_ate > valido_de),
    CONSTRAINT ck_token_prefixo CHECK (prefixo LIKE 'BRD-BR-__')
);

CREATE INDEX ix_token_vaga ON token (vaga_id);
